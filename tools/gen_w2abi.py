    "x_step",
    "quad16",
    "pair16",
    "mario_facing",
    "fall_v",
    "arc_idx",
    "jump_state",
    "victim_xy",
    "blit_behind",
    "w3_spawn_at",
    "award_stomp",
    # the vector block + the level binding
    "ovl_vec", "hdr_buf", "cur_level",
    # object slots (SoA)
    "o_type", "o_xl", "o_xh", "o_y", "o_vx", "o_vy", "o_tmr",
    "o_pvx", "o_pvy", "o_pdr", "o_st", "o_pw", "o_pfr", "o_hp",
    # spawning
    "spawn_tab", "find_free_obj", "obj_alloc_typed", "spawn_tabx",
    # world state
    "cam_x", "spr_x", "spr_y", "mario_big", "frame_count", "oi",
    "hurt_inv", "mario_grow", "mario_shrink",   # sub_off must mirror hurt_mario's
                                                # "this hit is thrown away" guard
    # drawing
    "draw_quad", "draw_tile_yflip", "dcol", "dy", "spr_subx", "do_flip",
    # combat / scoring
    "award_kill_at", "tmpL2", "tmpH2", "tmpH3", "tmpL", "tmpH",
