#!/usr/bin/env python3
"""
Generate build/w2abi.inc: engine-symbol equates for the standalone W2 overlay
build (src/w2code.s). The overlay is assembled AFTER the main link against the
addresses in its debug info, so it can call engine code and share its zero
page / BSS -- the same trick the GB uses for banked code, done at build time.

Usage: gen_w2abi.py <dbgfile> <out.inc>
"""
